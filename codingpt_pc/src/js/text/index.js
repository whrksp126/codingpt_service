// text/ — 화면에 나가는 **문구를 기능별 한 파일로 모으는 자리**(2026-08-04 사용자 확정).
//
// 왜 이렇게만 하나: 다국어(현재 목표 = 한국어·영어)는 다음 차수 작업이다. 지금 런타임 번역 계층을
//  통째로 넣으면 이번 기능 묶음의 작업량이 눈에 띄게 늘고, 기존 화면과 새 화면의 문구 처리 방식이
//  한동안 섞인다. 그래서 **구조만 미리 맞춰 둔다** — 새 기능의 문구는 코드에 흩뿌리지 않고 사전
//  파일 하나에 모으고, 나중에 언어를 켤 때 그 파일들만 손대면 되게.
//
// 규율:
//  · 사전은 `{ ko: {...}, en: {...} }` 모양이고 **키 집합이 같아야 한다**(en 이 비면 ko 로 떨어진다).
//  · 언어는 부팅 시 한 번 정해진다. 실행 중 전환은 아직 지원하지 않는다 — 지원하게 되면 `tx()` 를
//    호출하는 쪽이 아니라 여기서 구독을 열어 주는 방식으로 바꾼다(호출부는 그대로).
//  · 값에 문장 조립(`'파일 ' + n + '개'`)을 넣지 않는다. 언어마다 어순이 달라 조립이 깨진다 →
//    함수 값(`(n) => \`파일 ${n}개\``)으로 둔다.

const SUPPORTED = ['ko', 'en'];
let lang = 'ko';

/** 부팅 시 1회. 모르는 값은 한국어로 떨어진다. */
export function setLang(v) {
  lang = SUPPORTED.includes(v) ? v : 'ko';
}

export function getLang() {
  return lang;
}

/** 사전에서 현재 언어 묶음을 고른다. */
export function tx(dict) {
  if (!dict) return {};
  return dict[lang] || dict.ko || {};
}
